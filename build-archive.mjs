/**
 * Compile reports/<id>/ into a static archive block inside client.js.
 * The plugin deliberately serves no HTTP: Desktop's browserAccess policy blocks
 * ordinary browser requests, so all archive data must ship with the Client module.
 *
 * Run after adding or editing a report folder:
 *   node build-archive.mjs
 * Then refresh the Web GUI.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('.', import.meta.url));
const REPORTS = join(ROOT, 'reports');
const CLIENT = join(ROOT, 'client.js');
const BEGIN = '/* ARCHIVE:BEGIN generated by build-archive.mjs */';
const END = '/* ARCHIVE:END */';

function readJson(path) {
  try { return JSON.parse(readFileSync(path, 'utf8')); }
  catch (error) { throw new Error(`${path}: ${error.message}`); }
}

const items = readdirSync(REPORTS)
  .filter((id) => /^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(id) && statSync(join(REPORTS, id)).isDirectory())
  .map((id) => {
    const dir = join(REPORTS, id);
    const meta = readJson(join(dir, 'meta.json'));
    let html = '';
    try { html = readFileSync(join(dir, 'index.html'), 'utf8'); } catch { /* optional */ }
    return {
      id,
      title: meta.title || id,
      date: meta.date || '',
      topic: meta.topic || '',
      summary: meta.summary || '',
      coverage: meta.coverage || '',
      config: meta.config || { topic: meta.topic || '', platforms: [], keywords: [], notes: '' },
      candidates: meta.candidates || [],
      html,
    };
  })
  .sort((a, b) => String(b.date).localeCompare(String(a.date)));

const src = readFileSync(CLIENT, 'utf8');
const start = src.indexOf(BEGIN);
const end = src.indexOf(END);
if (start < 0 || end < 0 || end < start) {
  throw new Error('client.js is missing the ARCHIVE:BEGIN / ARCHIVE:END markers');
}
const payload = `const ARCHIVE = ${JSON.stringify(items, null, 2)};`;
const next = src.slice(0, start) + BEGIN + '\n' + payload + '\n    ' + src.slice(end);
writeFileSync(CLIENT, next);
console.log(`compiled ${items.length} report(s) into client.js (${Buffer.byteLength(payload)} bytes)`);
for (const it of items) console.log(`  ${it.date}  ${it.id}  html=${it.html.length} chars`);
